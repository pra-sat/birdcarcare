// สร้าง <option> ให้ช่องเลือกจังหวัด — กลุ่มที่เจอบ่อยอยู่บน แล้วคั่นด้วยเส้น
// selected = จังหวัดที่เลือกไว้ (ถ้ามี)
function plateProvinceOptions(selected) {
  var sel = String(selected || "");
  var esc = plateEsc;
  var out = ['<option value="">— เลือกจังหวัด —</option>'];

  out.push('<optgroup label="ที่เจอบ่อย">');
  PLATE_PROV_COMMON.forEach(function (p) {
    out.push('<option value="' + esc(p) + '"' + (p === sel ? ' selected' : '') + '>' + esc(p) + '</option>');
  });
  out.push('</optgroup>');

  out.push('<optgroup label="ทุกจังหวัด">');
  PLATE_PROV_ALL.forEach(function (p) {
    out.push('<option value="' + esc(p) + '"' + (p === sel ? ' selected' : '') + '>' + esc(p) + '</option>');
  });
  out.push('</optgroup>');

  return out.join('');
}

function plateEsc(v) {
  return String(v == null ? '' : v)
    .replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;').replace(/'/g, '&#39;');
}

// ── จัดรูปทะเบียนให้เหมือนกับที่ฝั่ง Apps Script ทำ (bcNormalizePlate_) ──
// ต้องให้ตรงกัน ไม่งั้นที่แสดงในแอปกับที่เก็บในชีตจะไม่เหมือนกัน
function platePretty(head, tail) {
  var h = String(head || '').trim().replace(/\s+/g, '');
  var t = String(tail || '').trim().replace(/\D/g, '');
  if (!h && !t) return '';
  return (h + ' ' + t).trim();
}

// ── ตัดตัวอักษรที่ใช้ในทะเบียนไทยไม่ได้ออก ────────────────────────────────
// ป้ายทะเบียนไทยใช้เลขอารบิกกับพยัญชนะไทยเท่านั้น ไม่มีภาษาอังกฤษ
// เรียกตอน input เพื่อไม่ให้พิมพ์อังกฤษลงไปได้ตั้งแต่แรก
// (แอดมินแจ้ง 13 ก.ย. 2569 ว่าใส่อังกฤษแล้วผ่าน)
//
// อนุญาต: 0-9 และ ก-ฮ  ·  ตัดทิ้ง: a-z A-Z สระ วรรณยุกต์ อักขระพิเศษ เว้นวรรค
// สระ/วรรณยุกต์ไม่ต้องมี เพราะหมวดทะเบียนใช้เฉพาะพยัญชนะ
function plateCleanHead(v) {
  return String(v == null ? '' : v).replace(/[^0-9ก-ฮ]/g, '');
}

// ── ตรวจความถูกต้อง ───────────────────────────────────────────────────────
// คืน { ok, warn }
//
// opts.required = true  -> ต้องกรอก (หน้าสมัครสมาชิก)
// opts.required = false -> เว้นว่างได้ (ค่าปริยาย)
//
// รูปแบบป้ายไทยที่รองรับ (หมวด = เลข 0-2 ตัว + พยัญชนะไทย 1-3 ตัว)
//   รถยนต์ใหม่   1กร 1723
//   รถยนต์เก่า   กข 1234
//   มอเตอร์ไซค์  1กก 1234 · ขก 123
//   ป้ายแดง      ป 1234
// ป้ายราชการ/ทูตที่รูปแบบต่างออกไป ให้แอดมินแก้ให้ทีหลังได้ในหน้าแอดมิน
function plateValidate(head, tail, opts) {
  var required = !!(opts && opts.required);
  var hRaw = String(head || '').trim();
  var t = String(tail || '').trim();
  var h = plateCleanHead(hRaw);

  if (!hRaw && !t) {
    return required
      ? { ok: false, warn: 'กรุณากรอกทะเบียนรถ' }
      : { ok: true, warn: '' };
  }

  // มีตัวอักษรที่ใช้ไม่ได้ปนมา (ส่วนใหญ่คือพิมพ์อังกฤษ)
  if (h !== hRaw.replace(/\s+/g, '')) {
    return { ok: false, warn: 'หมวดทะเบียนต้องเป็นภาษาไทยกับตัวเลขเท่านั้น เช่น 1กร หรือ ขค' };
  }

  if (!h) return { ok: false, warn: 'ยังไม่ได้กรอกหมวด (ตัวอักษรหน้า เช่น 1กร)' };
  if (!t) return { ok: false, warn: 'ยังไม่ได้กรอกเลขทะเบียน (ตัวเลขท้าย เช่น 1723)' };

  if (!/^\d{0,2}[ก-ฮ]{1,3}$/.test(h)) {
    return { ok: false, warn: 'หมวดต้องเป็นตัวเลข 0-2 ตัว แล้วตามด้วยพยัญชนะไทย 1-3 ตัว เช่น 1กร · ขค · ป' };
  }
  if (!/^\d{1,4}$/.test(t)) {
    return { ok: false, warn: 'เลขทะเบียนต้องเป็นตัวเลข 1-4 หลัก' };
  }
  return { ok: true, warn: '' };
}

// ── HTML ป้ายทะเบียนไทย (เลขบรรทัดบน จังหวัดบรรทัดล่าง) ───────────────────
// ใช้ทั้งหน้าสมาชิก หน้าแอดมิน และช่องแสดงตัวอย่างตอนกรอก
// dim = true -> สีเทา ใช้ตอนเป็นแค่ตัวอย่าง ยังไม่ได้บันทึก
function plateHtml(plate, province, dim) {
  var p = String(plate || '').trim();
  if (!p) return '';
  var cls = 'plate' + (dim ? ' is-dim' : '');
  return '<span class="' + cls + '">'
       + '<span class="num">' + plateEsc(p) + '</span>'
       + '<span class="prov">' + plateEsc(province || '—') + '</span>'
       + '</span>';
}
